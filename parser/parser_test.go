func TestStringLiteralExpressionParsing(t *testing.T) {
	input := `"hello world";`
	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	stmt := program.Statements[0].(*ast.ExpressionStatement)
	exp, ok := stmt.Expression.(*ast.StringLiteral)
	if !ok {
		t.Fatalf("stmt.Expression is not ast.StringLiteral, got=%T", stmt.Expression)
	}

	if exp.Value != "hello world" {
		t.Errorf("exp.Value is not %q, got=%q", "hello world", exp.Value)
	}
}

func TestArrayLiteralParsing(t *testing.T) {
	input := "[1, 2 * 2, 3 + 3]"

	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	stmt := program.Statements[0].(*ast.ExpressionStatement)
	array, ok := stmt.Expression.(*ast.ArrayLiteral)
	if !ok {
		t.Fatalf("exp not *ast.ArrayLiteral. got=%T", array)
	}
	if len(array.Elements) != 3 {
		t.Fatalf("len(array.Elements) not 3. got=%d", len(array.Elements))
	}
	if !testIntegerLiteral(t, array.Elements[0], 1) {
		t.Errorf("Couldn't parse first element")
	}
	if !testInfixExpression(t, array.Elements[1], 2, "*", 2) {
		t.Errorf("Couldn't parse second element")
	}
	if !testInfixExpression(t, array.Elements[2], 3, "+", 3) {
		t.Errorf("Couldn't parse third element")
	}

}
